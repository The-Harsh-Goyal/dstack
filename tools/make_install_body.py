#!/usr/bin/env python3
"""Write INSTALL_BODY.md: SKILL.md with the pack's absolute path filled in, for an agent that
loads the skill by pasting its body. It only writes a file; it registers nothing anywhere.

  python3 tools/make_install_body.py [--root /workspace/dstack] [-o INSTALL_BODY.md]
"""
import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]


def build(root: Path) -> str:
    body = (HERE / 'SKILL.md').read_text(encoding='utf-8')
    body = re.sub(r'\A---\n.*?\n---\n', '', body, flags=re.S)          # drop frontmatter
    body = body.replace('"$HD/', f'"{root}/').replace('$HD/', f'{root}/')
    head = (f'<!-- Generated by tools/make_install_body.py from SKILL.md. Pack root: {root}. '
            'Regenerate after editing SKILL.md; do not edit by hand. -->\n\n'
            f'> Pack root: `{root}` (references/, assets/, scripts/, demos/ are all under it). '
            f'Wherever a step says `$HD`, it means `{root}`.\n\n')
    return head + body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=str(HERE))
    ap.add_argument('-o', '--out', default=str(HERE / 'INSTALL_BODY.md'))
    a = ap.parse_args()
    Path(a.out).write_text(build(Path(a.root)), encoding='utf-8')
    print(f'Wrote {a.out}')


if __name__ == '__main__':
    main()
