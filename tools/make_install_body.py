def index(root):
    lines = ['\n---\n', '## Index: every script and reference (absolute paths)\n', '### Scripts\n']
    for rel in tracked('scripts'):
        if '/tests/' in rel or rel.startswith('scripts/tests') or '__pycache__' in rel:
            continue
        lines.append(f'- `{root}/{rel}`: {summary(rel)}')
    lines += ['', '### References\n']
    for rel in tracked('references'):
        if rel.endswith('.md'):
            lines.append(f'- [{rel}]({root}/{rel}): {summary(rel)}')
    lines += ['', '### Other\n',
              f'- `{root}/tools/doctor.sh`: setup and hook check (read-only)',
              f'- `{root}/assets/`: starter components (`animations.jsx`, `deck_stage.js`, device frames) and `style-specimens/`',
              f'- `{root}/demos/`: worked examples (`*-en.html` are the English versions)',
              f'- `{root}/HOSTS.md`, `{root}/SECURITY.md`: every outside host the pack can touch, and why',
              f'- `{root}/NOTICE`, `{root}/LICENSE`: MIT credit to alchaincyf/huashu-design', '']
    return '\n'.join(lines)


def build(root):
    return header(root) + skill_body(root).lstrip('\n') + index(root)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default=str(HERE))
    ap.add_argument('-o', '--out', default=str(HERE / 'INSTALL_BODY.md'))
    ap.add_argument('--check', action='store_true', help='exit 1 if the output file is out of date')
    a = ap.parse_args()
    text = build(a.root.rstrip('/'))
    out = Path(a.out)
    if a.check:
        same = out.exists() and out.read_text(encoding='utf-8') == text
        print(f'{out}: ' + ('up to date' if same else 'OUT OF DATE, regenerate'))
        sys.exit(0 if same else 1)
    out.write_text(text, encoding='utf-8')
    print(f'Wrote {out}')


if __name__ == '__main__':
    main()
